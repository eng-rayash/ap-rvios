/** لغة رسالة: أحرف عربية أكثر من اللاتينية = عربية. النموذج الخفيف يتبع لغة التعليمات
 *  (العربية) إن لم يُقل له صراحةً، فتُحسم اللغة هنا وتُذكر في آخر التعليمات */
export function replyLanguage(text: string): 'ar' | 'en' {
  const ar = (text.match(/\p{Script=Arabic}/gu) ?? []).length;
  const en = (text.match(/[A-Za-z]/g) ?? []).length;
  return en > ar ? 'en' : 'ar';
}

