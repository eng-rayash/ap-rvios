/**
 * AZM — التطبيع العربي
 *
 * البحث في النظام القديم كان `LIKE '%q%'` على الاسم الخام، فيفشل على
 * العربية فشلًا صامتًا: «احمد» لا يطابق «أحمد»، و«شركه» لا تطابق
 * «شركة»، و«مصطفي» لا يطابق «مصطفى».
 *
 * المستخدم لا يعرف أن بحثه فشل لسبب إملائي — يرى نتيجة فارغة ويظنّ
 * أن السجلّ غير موجود. وحلّال الكيانات في المرحلة ٦ يقوم أو يسقط على
 * هذا: «اجتمعت مع مدير شركة سحبكم» لن تُحلّ إن كُتب الاسم بهمزة
 * مختلفة عمّا في القاعدة.
 *
 * الحلّ: عمود `nameNormalized` مفهرس يُملأ بهذه الدالة عند كل كتابة،
 * والبحث يقع عليه لا على الاسم الخام.
 *
 * ⚠ الدالة نفسها **يجب أن تُنفَّذ على العميل أيضًا** بالسلوك ذاته:
 * البحث المحلي دون اتصال يمرّ على SQLite لا على الخادم. أي اختلاف
 * بين التطبيقين يعني نتائج مختلفة للاستعلام نفسه.
 */

/** تشكيل وعلامات إضافية تُحذف كليًّا. */
const DIACRITICS = /[ً-ٰٟۖ-ۭ]/g;

/** تطويل الكلمة — زخرفة لا تحمل معنى. */
const TATWEEL = /ـ/g;

/** صور الألف التي تُوحَّد. */
const ALEF_FORMS = /[آأإٱ]/g; // آ أ إ ٱ

/** أرقام عربية-هندية وفارسية تُحوَّل إلى لاتينية. */
const ARABIC_INDIC = /[٠-٩]/g;
const EXTENDED_INDIC = /[۰-۹]/g;

/**
 * يطبّع نصًّا عربيًا للبحث والمطابقة.
 *
 * ما يفعله، بالترتيب:
 *   ١. توحيد Unicode (NFKC) — يفكّ الأشكال المركّبة
 *   ٢. حذف التشكيل والتطويل
 *   ٣. توحيد الألف: آ أ إ ٱ ← ا
 *   ٤. توحيد التاء المربوطة: ة ← ه
 *   ٥. توحيد الألف المقصورة: ى ← ي
 *   ٦. توحيد الهمزات: ؤ ← و · ئ ← ي
 *   ٧. تحويل الأرقام الهندية إلى لاتينية
 *   ٨. خفض حروف اللاتينية
 *   ٩. ضغط المسافات
 *
 * ما لا يفعله عمدًا: لا يحذف «ال» التعريف. «الرياض» و«رياض» اسمان
 * مختلفان، ودمجهما يخلط شركات منفصلة.
 */
export function normalizeArabic(input: string): string {
  if (!input) return '';

  return input
    .normalize('NFKC')
    .replace(DIACRITICS, '')
    .replace(TATWEEL, '')
    .replace(ALEF_FORMS, 'ا') // ا
    .replace(/ة/g, 'ه') // ة ← ه
    .replace(/ى/g, 'ي') // ى ← ي
    .replace(/ؤ/g, 'و') // ؤ ← و
    .replace(/ئ/g, 'ي') // ئ ← ي
    .replace(ARABIC_INDIC, (d) =>
      String.fromCharCode(d.charCodeAt(0) - 0x0660 + 48),
    )
    .replace(EXTENDED_INDIC, (d) =>
      String.fromCharCode(d.charCodeAt(0) - 0x06f0 + 48),
    )
    .toLowerCase()
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * هل يطابق [needle] النصَّ [haystack] بعد التطبيع؟
 *
 * مطابقة احتواء لا تساوٍ: المستخدم يكتب «سحبكم» ويقصد «شركة سحبكم
 * للتجارة».
 */
export function matchesNormalized(haystack: string, needle: string): boolean {
  const n = normalizeArabic(needle);
  if (!n) return false;
  return normalizeArabic(haystack).includes(n);
}
